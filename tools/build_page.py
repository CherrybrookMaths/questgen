#!/usr/bin/env python3
"""Assemble the review page (site/review.html) from page_src/.

Rule (owner 14 Nov, hardening): edit page_src/, then run this; never edit site/review.html by hand.

page_src/ layout (NOT src/: src/<id>.pdf and src/hsc/ are the staged exam PDFs of the import):
  page_src/page.html    the markup shell: head tags, then <!-- build:styles -->, the body markup, then <!-- build:scripts -->
  page_src/css/*.css    the stylesheet, one file per feature; concatenated IN THE ORDER LISTED in build.json (cascade order matters)
  page_src/js/*.js      the scripts, one file per feature, in load order
  page_src/build.json   {"template": "page.html",
                    "styles":  [[css files of one <style> block], ...],
                    "scripts": [[js files of one <script> block], {"src": "<url of an external script>"}, ...]}
                   Files listed together in one inner list share ONE <script> block (top-level function declarations are
                   hoisted across them, exactly as in the old single main script). Each inner list is its own block,
                   so an error in one block does not stop the others.

Output is deterministic (no timestamps): the same page_src/ always gives the same bytes. The first line is a comment that
says the file is generated.

Usage:
  python3 tools/build_page.py            build site/review.html and print a size summary
  python3 tools/build_page.py --check    exit 1 if site/review.html differs from what page_src/ would build (nothing written)
  python3 tools/build_page.py --out F    write to F instead of site/review.html

Vendor files (hardening action 3): every build (and --check) also verifies site/vendor/ against tools/vendor_manifest.json
(tools/vendor.py), checks that every vendor/... file the page names is in the manifest, and refuses a page that still
names a public CDN (cdn.jsdelivr.net, unpkg.com, cdnjs). Any problem exits 1 and nothing is written.
"""
import hashlib, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'page_src'
OUT = ROOT / 'site' / 'review.html'
BANNER = '<!-- Generated from page_src/ by tools/build_page.py. Do not edit this file: edit page_src/ and rebuild. -->\n'


def read(rel):
    p = SRC / rel
    t = p.read_text(encoding='utf8')
    if t and not t.endswith('\n'):
        t += '\n'
    return t


def build():
    cfg = json.loads((SRC / 'build.json').read_text(encoding='utf8'))
    tpl = (SRC / cfg['template']).read_text(encoding='utf8')
    assert tpl.count('<!-- build:styles -->') == 1 and tpl.count('<!-- build:scripts -->\n') == 1, 'page.html needs one of each build marker'
    sizes = []                      # (kind, name, bytes)
    seen = set()
    styles = []
    for blk in cfg['styles']:
        parts = []
        for f in blk:
            assert f not in seen, f'{f} listed twice'; seen.add(f)
            t = read(f)
            assert '</style' not in t.lower(), f'{f} contains a closing style tag'
            parts.append(t); sizes.append(('css', f, len(t.encode('utf8'))))
        styles.append('<style>\n' + ''.join(parts) + '</style>')
    scripts = []
    for blk in cfg['scripts']:
        if isinstance(blk, dict):
            assert set(blk) == {'src'}, blk
            scripts.append(f'<script src="{blk["src"]}"></script>\n'); sizes.append(('ext', blk['src'], 0))
            continue
        parts = []
        for f in blk:
            assert f not in seen, f'{f} listed twice'; seen.add(f)
            t = read(f)
            assert not re.search(r'</script', t, re.I), f'{f} contains a literal closing script tag (write <\\/script> in strings)'
            parts.append(t); sizes.append(('js', f, len(t.encode('utf8'))))
        scripts.append('<script>\n' + ''.join(parts) + '</script>\n')
    # every css/js file in page_src/ must be listed (a forgotten file is a silent bug)
    on_disk = {str(p.relative_to(SRC)) for d in ('css', 'js') for p in (SRC / d).glob('*') if p.suffix in ('.css', '.js')}
    missing = sorted(on_disk - seen)
    assert not missing, f'not listed in page_src/build.json: {missing}'
    html = BANNER + tpl.replace('<!-- build:styles -->', '\n'.join(styles)).replace('<!-- build:scripts -->\n', ''.join(scripts))
    return html, sizes, len(styles), sum(1 for s in scripts if not s.startswith('<script src'))


def vendor_problems(html):
    """site/vendor/ matches tools/vendor_manifest.json, the page names only vendored files, and no public CDN."""
    sys.path.insert(0, str(ROOT / 'tools'))
    import vendor
    errs = vendor.check(quiet=True)
    known = vendor.manifest_paths()
    refs = set(re.findall(r"vendor/[\w@.\-/]+\.(?:js|css|woff2)", html))
    refs |= {'vendor/' + m for m in re.findall(r"VENDOR\+'([\w@.\-/]+\.(?:js|css|woff2))'", html)}
    errs += [f'page names {r}, which is not in tools/vendor_manifest.json' for r in sorted(refs - known)]
    for cdn in ('cdn.jsdelivr.net', 'unpkg.com', 'cdnjs.cloudflare.com'):
        if cdn in html:
            errs.append(f'page still names the public CDN {cdn}')
    if re.search(r'<script[^>]+src="https?:', html):
        errs.append('page has a <script src> on another host')
    return errs, len(refs)


VERSIONED = ('data/bank/**/*.json', 'data/img/*.json', 'data/cmp/*.json', 'data/assets.json', 'project/open_decisions.json')


def stamp(html):
    """Replace the page's '__QG_BUILD__' with a 16-hex id of the page and every file under VERSIONED (site/)."""
    assert html.count("'__QG_BUILD__'") == 1, "page_src/js/37_fresh.js must hold '__QG_BUILD__' exactly once"
    h = hashlib.sha256(html.encode('utf8'))
    site = OUT.parent
    for f in sorted({p for g in VERSIONED for p in site.glob(g) if p.is_file()}):
        h.update(str(f.relative_to(site)).encode() + b'\0' + f.read_bytes())
    bid = h.hexdigest()[:16]
    return html.replace("'__QG_BUILD__'", "'" + bid + "'"), bid


def write_version(bid):
    """site/data/version.json = {"build": id}; left alone when unchanged (so its date stays)."""
    f = OUT.parent / 'data' / 'version.json'
    data = json.dumps({'build': bid}).encode() + b'\n'
    if not f.exists() or f.read_bytes() != data:
        f.write_bytes(data)


def main(argv):
    out = OUT
    if '--out' in argv:
        out = pathlib.Path(argv[argv.index('--out') + 1])
    html, sizes, nstyle, nscript = build()
    # owner 23 Nov: "stale page approvals" (page_src/js/37_fresh.js): one id for this build, from the page and the files it shows;
    # the page carries it and data/version.json repeats it, so an open page can tell when a newer version is live
    html, build_id = stamp(html)
    data = html.encode('utf8')
    verrs, nrefs = vendor_problems(html)
    if verrs:
        print('VENDOR PROBLEMS (run python3 tools/vendor.py --check):'); [print('  ' + e) for e in verrs[:30]]
        return 1
    if '--check' in argv:
        cur = out.read_bytes() if out.exists() else b''
        if cur == data:
            print(f'up to date: {out} ({len(data):,} bytes, sha256 {hashlib.sha256(data).hexdigest()[:12]})'); return 0
        print(f'OUT OF DATE: {out} differs from page_src/ (run python3 tools/build_page.py; never edit {out.name} by hand)'); return 1
    if out == OUT and '--check' not in argv:
        write_version(build_id)
    if out.exists() and out.read_bytes() == data:   # unchanged: leave the file (and its mtime) alone, so a passed page test stays valid
        print(f'unchanged: {out} ({len(data):,} bytes, sha256 {hashlib.sha256(data).hexdigest()[:12]})'); return 0
    out.write_bytes(data)
    css =sum(n for k, _, n in sizes if k == 'css'); js = sum(n for k, _, n in sizes if k == 'js')
    print(f'built {out}: {len(data):,} bytes, sha256 {hashlib.sha256(data).hexdigest()[:12]}')
    print(f'  css  {css:>9,} bytes in {sum(1 for k,_,_ in sizes if k=="css")} files, {nstyle} <style> block(s)')
    print(f'  js   {js:>9,} bytes in {sum(1 for k,_,_ in sizes if k=="js")} files, {nscript} <script> block(s)')
    for k, f, n in sizes:
        print(f'    {k:3} {n:>8,}  {f}')
    print(f'  markup + head {len(data) - css - js:,} bytes')
    print(f'  vendor OK: {nrefs} vendor file(s) named by the page, all in tools/vendor_manifest.json; site/vendor/ matches it')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
